#!/usr/bin/env bun
// Regenerates MATRIX.md.
//
// The matrix has a column per (target, model) pair rather than per target,
// because "OpenAI-compatible" turns out to vary WITHIN a provider: gpt-4o-mini
// and gpt-5.4-mini are the same endpoint, the same account and the same request
// builder, and they disagree about the name of the token-budget parameter and
// the name of the system role. A per-provider matrix would hide that.
//
// Each pair is a separate process so one target dying cannot take the run with
// it. Keys come from the environment; none are read from or written to this repo.

import { TARGETS, missingEnv } from '../src/targets.ts';
import { markdownMatrix } from '../src/report.ts';
import type { TargetReport } from '../src/types.ts';

interface Pair {
  target: string;
  model?: string;
  /** Minutes to allow; local models are slow. */
  timeoutMs?: number;
}

const PAIRS: Pair[] = [
  { target: 'openai', model: 'gpt-4o-mini' },
  { target: 'openai', model: 'gpt-5.4-mini' },
  { target: 'cloudflare' },
  { target: 'ollama', model: 'qwen3:8b', timeoutMs: 300_000 },
  { target: 'deepseek' },
  { target: 'openrouter' },
  { target: 'xai' },
  { target: 'groq' },
];

const reports: TargetReport[] = [];

for (const pair of PAIRS) {
  const target = TARGETS[pair.target];
  if (!target) throw new Error(`unknown target in PAIRS: ${pair.target}`);
  const label = `${pair.target}${pair.model ? ` / ${pair.model}` : ''}`;

  if (missingEnv(target).length) {
    console.error(`skip  ${label} — missing ${missingEnv(target).join(', ')}`);
    continue;
  }

  console.error(`run   ${label}`);
  const args = ['run', 'src/cli.ts', '--target', pair.target, '--json'];
  if (pair.model) args.push('--model', pair.model);

  const proc = Bun.spawnSync(['bun', ...args], {
    env: {
      ...process.env,
      ...(pair.timeoutMs ? { WIRECHECK_TIMEOUT_MS: String(pair.timeoutMs) } : {}),
    },
    stderr: 'inherit',
  });

  const out = proc.stdout.toString().trim();
  if (!out) {
    console.error(`      no output — skipped`);
    continue;
  }
  try {
    const parsed = JSON.parse(out) as { reports: TargetReport[] };
    for (const r of parsed.reports) {
      // Label by pair, so two models on one endpoint are two columns.
      reports.push({ ...r, target: label });
    }
  } catch {
    console.error(`      unparseable output — skipped`);
  }
}

if (!reports.length) {
  console.error('\nNo target produced a report. Set at least one provider key, or run Ollama.');
  process.exit(1);
}

const header = `# Measured conformance matrix

Generated by \`bun run scripts/build-matrix.ts\` on ${new Date().toISOString().slice(0, 10)}.

Every cell is a live call made at generation time. Nothing here is asserted from
documentation. A \`≠\` is **not** a complaint about the provider — it is a thing
your client code has to handle.

Reference column is \`openai / gpt-4o-mini\`; divergence is measured against
whatever it does.

`;

const footer = `
## Reading this

- Two columns for \`openai\` are not a mistake. The same endpoint, account and
  request builder behave differently depending on the model string, which is the
  single most surprising result in here.
- \`deepseek\` and \`openrouter\` are shown unreachable rather than divergent
  because both accounts are at zero balance. An endpoint returning HTTP 402 has
  not read your request body, so no conformance conclusion can be drawn from it.
  Earlier versions of this tool did draw them anyway — see the README.
- Local \`ollama\` timings are from an 8 GB M1 at roughly 1.6 tokens/sec. Treat
  them as evidence of *behaviour*, not of speed.
`;

await Bun.write('MATRIX.md', header + markdownMatrix(reports) + footer);
console.error(`\nwrote MATRIX.md — ${reports.length} column(s)`);
